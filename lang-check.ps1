# Translations helper for AppSys.
#   powershell -ExecutionPolicy Bypass -File lang-check.ps1
# - writes lang\_template.txt with every English text found in the sources (L.T / L.F / Mi / Toggle calls)
# - for each lang\<code>.txt reports missing texts, obsolete texts and placeholder mistakes
# All the .cs files in this folder are scanned, so new source files need no change here.
param([switch]$Quiet)
$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
$langDir = Join-Path $root 'lang'

$lit = '"(?:[^"\\]|\\.)*"'
$arg = "$lit(?:\s*\+\s*$lit)*"
$call = [regex]"(?:\bL\.[TF]\(|\bMi\(|\bToggle\(\s*\w+\s*,)\s*$arg\s*,\s*(?<en>$arg)"
# {0}, {1} and also formatted placeholders such as {0:0} or {0:0.0}
$ph = '\{\d+(?::[^{}]*)?\}'

function Join-Literals([string]$s) {
    $parts = [regex]::Matches($s, '"((?:[^"\\]|\\.)*)"') | ForEach-Object { $_.Groups[1].Value }
    # keep \n as the two characters \n (same escape used in the .txt files)
    return (($parts -join '') -replace '\\"', '"' -replace '\\\\', '\')
}

function Placeholders([string]$s) {
    return ([regex]::Matches($s, $ph) | ForEach-Object { $_.Value } | Sort-Object) -join ','
}

$keys = New-Object System.Collections.Generic.List[string]
foreach ($f in Get-ChildItem $root -Filter *.cs | Sort-Object Name) {
    $src = Get-Content -Raw -Encoding UTF8 $f.FullName
    foreach ($m in $call.Matches($src)) {
        $k = Join-Literals $m.Groups['en'].Value
        if (-not $keys.Contains($k)) { $keys.Add($k) }
    }
}

$header = @(
    '# AppSys translation template - generated by lang-check.ps1, do not edit this file.',
    '# Copy it to lang\<code>.txt (e.g. de.txt, fr.txt, pt-BR.txt) and write the translation after " = ".',
    '# Keep {0}, {1}, {0:0} placeholders and \n line breaks. Empty lines stay in English.',
    '',
    'language = '
)
$out = $header + ($keys | ForEach-Object { "$_ = " })
New-Item -ItemType Directory -Force $langDir | Out-Null
Set-Content -Encoding UTF8 (Join-Path $langDir '_template.txt') $out
if (-not $Quiet) { Write-Host ("lang\_template.txt: {0} texts" -f $keys.Count) }

$problems = 0
foreach ($file in Get-ChildItem $langDir -Filter *.txt | Where-Object { $_.BaseName -ne '_template' }) {
    $tr = @{}
    $name = $file.BaseName
    foreach ($ln in Get-Content -Encoding UTF8 $file.FullName) {
        $t = $ln.Trim()
        if ($t -eq '' -or $t.StartsWith('#')) { continue }
        $i = $t.IndexOf(' = ')
        if ($i -le 0) { continue }
        $k = $t.Substring(0, $i).Trim(); $v = $t.Substring($i + 3).Trim()
        if ($k -eq 'language') { if ($v) { $name = $v }; continue }
        $tr[$k] = $v
    }
    $missing = @($keys | Where-Object { -not $tr.ContainsKey($_) -or $tr[$_] -eq '' })
    $obsolete = @($tr.Keys | Where-Object { -not $keys.Contains($_) })
    $badPh = @($keys | Where-Object { $tr.ContainsKey($_) -and $tr[$_] -ne '' } | Where-Object { (Placeholders $_) -ne (Placeholders $tr[$_]) })
    Write-Host ("{0} ({1}): {2}/{3} translated" -f $file.Name, $name, ($keys.Count - $missing.Count), $keys.Count)
    foreach ($k in $missing) { Write-Host "  missing:     $k" }
    foreach ($k in $obsolete) { Write-Host "  obsolete:    $k" }
    foreach ($k in $badPh) { Write-Host "  placeholder: $k" }
    $problems += $badPh.Count
}
if ($problems -gt 0) { exit 1 }
